  function _kanaToHangul(str) {
    if (!str) return '';
    let res = '';
    for (const ch of str) {
      res += _KANA_MAP[ch] || ch;
    }
    return res;
  }

  function formatPlayerKorean(name) {
    if (!name || name === '-') return '-';
    let clean = String(name).trim();

    // 1. window.formatPlayerKorean (player_ko_map.js) 우선 시도
    if (typeof window !== 'undefined' && typeof window.formatPlayerKorean === 'function' && window.formatPlayerKorean !== formatPlayerKorean) {
      try {
        const tr = window.formatPlayerKorean(clean);
        if (tr && !/[\u4e00-\u9fff\u3040-\u30ff]/.test(tr)) {
          return tr;
        }
        clean = tr || clean;
      } catch(e) {}
    }

    // 2. 직접 매핑 테이블 확인
    if (_NPB_PLAYER_MAP[clean]) return _NPB_PLAYER_MAP[clean];
    const noSpace = clean.replace(/\s+/g, '');
    if (_NPB_PLAYER_MAP[noSpace]) return _NPB_PLAYER_MAP[noSpace];

    // 복합 잔여어 정리 (예: '마에다 健藤平' -> '마에다 켄타', '코지마 横山' -> '코지마 카즈야', '오오세라 森浦' -> '오오세라 다이치')
    if (clean.includes('健藤平') || clean.includes('마에다')) {
      if (clean.includes('마에다')) return '마에다 켄타';
    }
    if (clean.includes('코지마') || clean.includes('横山')) {
      if (clean.includes('코지마')) return '코지마 카즈야';
    }
    if (clean.includes('오오세라') || clean.includes('森浦')) {
      if (clean.includes('오오세라')) return '오오세라 다이치';
    }
    if (clean.includes('쿠도') || clean.includes('工藤')) {
      return '쿠도 야스키';
    }

    // 3. 부분 치환 검사
    for (const [k, v] of Object.entries(_NPB_PLAYER_MAP)) {
      if (k.length >= 2 && clean.includes(k)) {
        clean = clean.replace(new RegExp(k, 'g'), v);
      }
    }

    // 4. 가타카나 음차 변환
    if (/[\u30a0-\u30ff]/.test(clean)) {
      clean = _kanaToHangul(clean);
    }

    // 5. 남은 한자 정제 (한글과 섞여있을 때 한자만 떨어뜨림)
    if (/[\u4e00-\u9fff]/.test(clean)) {
      clean = clean.replace(/[\u4e00-\u9fff]+/g, '').trim();
    }

    return clean || String(name).trim();
  }

  function formatKSTDateTime(dateStr) {
    if (!dateStr) return '-';
    try {
      if (dateStr.includes('T') || dateStr.includes('-')) {
        const d = new Date(dateStr);
        if (!isNaN(d.getTime())) {
          const m = String(d.getMonth() + 1).padStart(2, '0');
          const day = String(d.getDate()).padStart(2, '0');
          const h = String(d.getHours()).padStart(2, '0');
          const min = String(d.getMinutes()).padStart(2, '0');
          return `${m}-${day} ${h}:${min}`;
        }
      }
      return dateStr.replace(/(\d{4}-)/g, '').substring(0, 11);
    } catch(e) {
      return dateStr;
    }
  }

